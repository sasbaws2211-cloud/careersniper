# Boards that matched the wrong company (found by spot-checking real job pages) or are dead. Never (re)added by the
# seed list or by discovery, so removing one is permanent.
BLOCKED = {
    ("lever", "blue"), ("lever", "fly"), ("lever", "neon"), ("lever", "veo"), ("lever", "mistral"),
    ("ashby", "collective"), ("ashby", "dapper"), ("ashby", "flock"), ("ashby", "vivid"), ("ashby", "sonder"),
    ("ashby", "astra"), ("ashby", "flink"), ("ashby", "sweep"), ("greenhouse", "carbon"),
    ("greenhouse", "archer"), ("greenhouse", "axiom"), ("greenhouse", "beyond"), ("greenhouse", "cleo"),
    ("greenhouse", "spin"), ("greenhouse", "wise"),
}


def is_blocked(ats: str, token: str) -> bool:
    return (ats, token.lower()) in BLOCKED


async def seed_registry(db: AsyncSession) -> int:
    added = 0
    for ats, token, name in STARTER:
        if is_blocked(ats, token):
            continue
        if not (await db.scalar(select(Company).where(Company.ats == ats, Company.board_token == token))):
            db.add(Company(name=name, ats=ats, board_token=token, active=True))
            added += 1
    await db.commit()
    return added
